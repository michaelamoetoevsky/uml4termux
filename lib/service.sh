# shellcheck shell=bash
#
# uml4termux — lib/service.sh
# Runit service: the guest runs as an independent runtime service on Termux.
#
#   $PREFIX/var/service/uml4termux/
#   ├── run        exec uml4termux boot --foreground  (stays attached)
#   ├── finish     wake-unlock + stop cleanup on any exit
#   └── log/run    svlogd
#
# One service supervises the whole stack: runit restarts the run script when
# it exits, which boots a fresh gvproxy + guest (the in-process gvproxy
# supervisor still handles fast BESS-EOF restarts inside one boot).  Services
# auto-start when Termux boots; add a 'down' file to opt out.
#
# Wake lock: acquired in run, released in finish — that covers every exit
# path runit knows about (down, crash, restart).
#
# Phantom process killer (Android 12+): a supervised guest plus dockerd plus
# containers is many processes.  See docs/MOBILITY.md §2 (Developer options ->
# disable child process restrictions, or the adb device_config one-liner
# printed by 'uml4termux doctor').
#
# SPDX-License-Identifier: GPL-2.0-only

UML4TERMUX_SVDIR="${UML4TERMUX_SVDIR:-${PREFIX:-/data/data/com.termux/files/usr}/var/service}"

svc_name()      { printf 'uml4termux'; }
svc_dir()       { printf '%s/%s' "${UML4TERMUX_SVDIR}" "$(svc_name)"; }
svc_have_runit() { command -v sv >/dev/null 2>&1 && [ -d "${UML4TERMUX_SVDIR}" ]; }

svc_run_script() {
  cat <<'RUN'
#!/data/data/com.termux/files/usr/bin/bash
# uml4termux service (generated by lib/service.sh -- do not edit by hand).
# runit restarts this script whenever it exits: the guest self-heals.
# Phantom process killer (Android 12+): see docs/MOBILITY.md section 2 —
# a guest plus dockerd plus containers is many processes.
exec 2>&1
umask 077
# Optional per-device overrides (e.g. UML4TERMUX_HOME pointing at a
# non-default asset directory) live in this file.
ENV_FILE="${HOME}/.config/uml4termux/service.env"
[ -r "${ENV_FILE}" ] && . "${ENV_FILE}"

BIN="${HOME}/.local/bin/uml4termux"
[ -x "${BIN}" ] || BIN="${PREFIX}/bin/uml4termux"
[ -x "${BIN}" ] || { echo "uml4termux binary not found"; sleep 300; exit 1; }

# Slow the restart loop when the assets have not been fetched yet.
if "${BIN}" dist-info 2>/dev/null | grep -q 'state=missing'; then
  echo "$(date) assets missing/incomplete; sleeping 5 min before retry"
  sleep 300
  exit 1
fi

# Hold a wake lock for the lifetime of the service: without it, Android
# freezes the app when the screen is off and the guest stops making progress.
"${BIN}" wakelock on >/dev/null 2>&1 \
  || echo "WARNING: no wake lock; the guest may freeze when the screen is off"

echo "$(date) booting the UML guest under runit supervision"
# 'docker --foreground' is the full runbook: gvproxy + guest + dockerd +
# expose the published ports on the phone's loopback, then stay attached
# until the guest powers off (runit restarts the whole stack after that).
exec "${BIN}" docker --foreground
RUN
}

svc_finish_script() {
  cat <<'FINISH'
#!/data/data/com.termux/files/usr/bin/bash
# Release the wake lock no matter why the service stopped, and leave the
# instance state clean for the next run.
BIN="${HOME}/.local/bin/uml4termux"
[ -x "${BIN}" ] || BIN="${PREFIX}/bin/uml4termux"
"${BIN}" wakelock off >/dev/null 2>&1 || termux-wake-unlock >/dev/null 2>&1 || true
"${BIN}" stop >/dev/null 2>&1 || true
FINISH
}

svc_log_script() {
  cat <<'RUN'
#!/data/data/com.termux/files/usr/bin/bash
# runsv runs this with cwd = <service>/log, so the svlogd dir is ./main
exec svlogd -tt ./main
RUN
}

svc_write() {  # svc_write <dir> <file> <generator-function-name>
  local dir="$1" file="$2" fn="$3"
  mkdir -p "${dir}/log/main"
  "${fn}" >"${dir}/${file}"
  chmod +x "${dir}/${file}"
}

svc_install() {
  if ! svc_have_runit; then
    err "runit is not available (no 'sv' command or no ${UML4TERMUX_SVDIR})"
    return 1
  fi
  local dir; dir="$(svc_dir)"
  if uml4termux_is_dry_run; then
    printf '+ mkdir -p %s/log/main\n' "${dir}"
    printf '+ write run, finish, log/run (exec uml4termux boot --foreground)\n'
    return 0
  fi
  svc_write "${dir}" run svc_run_script
  svc_write "${dir}" finish svc_finish_script
  svc_write "${dir}" log/run svc_log_script
  ok "service installed: ${dir}"
  info "start now : sv up $(svc_name)"
  info "autostart : on Termux boot (remove by touching ${dir}/down)"
  info "logs      : svlogd under ${dir}/log/main, or 'uml4termux service logs'"
}

svc_remove() {
  if uml4termux_is_dry_run; then
    printf '+ sv down + rm -rf %s\n' "$(svc_dir)"
    return 0
  fi
  sv down "$(svc_name)" 2>/dev/null || true
  sleep 2
  rm -rf "$(svc_dir)"
  ok "service removed"
}

svc_status() {
  if ! svc_have_runit; then
    err "runit is not available"
    return 1
  fi
  sv status "$(svc_name)" 2>&1
  if uml4termux_wakelock_held 2>/dev/null; then
    info "wake lock: held"
  fi
  return 0
}

svc_start() {
  [ -f "$(svc_dir)/run" ] || { err "service not installed; run 'uml4termux service install'"; return 1; }
  sv up "$(svc_name)"
}

svc_stop() {
  sv down "$(svc_name)" 2>/dev/null || true
}

svc_logs() {
  local main; main="$(svc_dir)/log/main"
  [ -d "${main}" ] || { err "no logs yet (${main})"; return 1; }
  tail -n "${1:-100}" "${main}/current" 2>/dev/null || cat "${main}/current" 2>/dev/null
}
