# ---------------------------------------------------------------------------
# proot wrapper
# ---------------------------------------------------------------------------
# gvproxy reads /etc/resolv.conf for its upstream DNS.  Android has none, and
# Termux cannot create it, so gvproxy runs under `proot -b $PREFIX/etc:/etc`.
# On a normal Linux host the real /etc/resolv.conf exists and proot is
# unnecessary (and may not be installed).
net_proot_wanted() {
  case "${UML4TERMUX_GVPROXY_PROOT}" in
    always) return 0 ;;
    never)  return 1 ;;
  esac
  command -v proot >/dev/null 2>&1 || return 1
  [ -r /etc/resolv.conf ] && return 1
  [ -r "${PREFIX}/etc/resolv.conf" ] || return 1
  return 0
}

net_gvproxy_argv() {
  # echoes the argv (one line, shell-quoted) and sets the global GV_ARGV array
  GV_ARGV=()
  if net_proot_wanted; then
    GV_ARGV+=(proot -b "${PREFIX}/etc:/etc")
  fi
  GV_ARGV+=("$(uml4termux_asset_path gvproxy)")
  GV_ARGV+=(-debug
            -listen "unix://${UML4TERMUX_GVNET_SOCK}"
            -listen-bess "unixpacket://${UML4TERMUX_BESS_SOCK}"
            -log-file "${UML4TERMUX_GVPROXY_LOG}")
  uml4termux_quote "${GV_ARGV[@]}"
}

# ---------------------------------------------------------------------------
# start / readiness / stop
# ---------------------------------------------------------------------------
net_start_gvproxy() {
  uml4termux_require_assets gvproxy
  local bin; bin="$(uml4termux_asset_path gvproxy)"
  uml4termux_runtime_init

  step "starting gvproxy (BESS bridge: ${UML4TERMUX_BESS_SOCK})"
  # A previous UML run leaves the BESS peer gone and gvproxy dead: never reuse
  # sockets, always start a fresh process for this run.
  if ! uml4termux_is_dry_run; then
    rm -f "${UML4TERMUX_GVNET_SOCK}" "${UML4TERMUX_BESS_SOCK}"
    # The log directory may not exist in a fresh service context (runit runs
    # the service before any interactive command has created it).
    mkdir -p "$(dirname "${UML4TERMUX_GVPROXY_LOG}")"
    : > "${UML4TERMUX_GVPROXY_LOG}"
  else
    printf '+ rm -f %s %s\n' "$(uml4termux_quote "${UML4TERMUX_GVNET_SOCK}" "${UML4TERMUX_BESS_SOCK}")" ""
    printf '+ : > %s\n' "${UML4TERMUX_GVPROXY_LOG}"
  fi

  if net_proot_wanted; then
    info "proot -b ${PREFIX}/etc:/etc (gvproxy needs /etc/resolv.conf)"
  else
    info "no proot wrapper needed on this host (or UML4TERMUX_GVPROXY_PROOT=never)"
  fi

  # gvproxy is started under a supervisor, not directly: it exits whenever its
  # BESS peer disconnects, and it drops every port forward when it does. The
  # supervisor restarts it for the lifetime of the UML instance and re-applies
  # the exposures recorded in ${UML4TERMUX_RUNTIME}/expose.list.
  local sup proot_flag=0
  net_proot_wanted && proot_flag=1
  sup="${UML4TERMUX_RUNTIME}/gvproxy-supervisor.sh"
  # The supervisor reads its configuration from the environment, not from argv:
  # a child only inherits *exported* variables, and these are set with defaults
  # but were never exported (the old code passed them on the command line).
  export UML4TERMUX_GVNET_SOCK UML4TERMUX_BESS_SOCK UML4TERMUX_GVPROXY_LOG UML4TERMUX_GUEST_IP
  if uml4termux_is_dry_run; then
    printf '+ write %s (gvproxy supervisor)\n' "$(uml4termux_quote "${sup}")"
    printf '+ spawn gvproxy supervisor: bash %s %s %d\n' \
      "$(uml4termux_quote "${sup}")" "$(uml4termux_quote "${bin}")" "${proot_flag}"
  else
    net_gvproxy_supervisor_script >"${sup}"
    chmod +x "${sup}"
  fi
  uml4termux_spawn gvproxy /dev/null bash "${sup}" "${bin}" "${proot_flag}"

  net_wait_ready "${UML4TERMUX_GVPROXY_READY_TIMEOUT:-40}" || return 1
  net_expose_apply_all
}

net_gvproxy_supervisor_script() {
  # Stdout: the supervisor script. Editable only through this function so the
  # spawned copy and the checked-in source cannot drift.
  cat <<'SUP'
#!/usr/bin/env bash
# gvproxy supervisor (generated by lib/net.sh -- do not edit by hand).
#
# Why: gvproxy exits when its BESS peer disconnects, which happens the moment a
# UML run ends, and it drops every forward when it does. This loop keeps it
# alive for as long as the UML instance is alive and re-applies the exposures
# recorded in $UML4TERMUX_RUNTIME/expose.list after every restart.
#
# Argument 1: gvproxy binary. Argument 2: 1 = run under proot (Android has no
# /etc/resolv.conf for gvproxy to read), 0 = run directly.
set -u
bin="$1"
proot_flag="$2"
runtime="${UML4TERMUX_RUNTIME}"
pidfile="${runtime}/gvproxy.pid"
reg="${runtime}/expose.list"
child=""

# A dead child that the parent has not waited for stays in the process table as
# a zombie, and 'kill -0' succeeds for zombies. Treating that as "alive" would
# restart gvproxy forever after its UML was gone, so read the real state.
upid_alive() {
  local stat rest
  stat="$(cat "/proc/${1}/stat" 2>/dev/null)" || return 1
  rest="${stat##*) }"
  set -- ${rest}
  [ "${1:-Z}" != "Z" ]
}

cleanup() {
  if [ -n "${child}" ]; then
    # Kill the tracee first (children of the wrapper), then the wrapper:
    # proot swallows SIGTERM instead of forwarding it, and pkill -P targets by
    # parent pid, so this never touches an unrelated process.
    pkill -TERM -P "${child}" 2>/dev/null || true
    kill "${child}" 2>/dev/null || true
  fi
  rm -f "${UML4TERMUX_GVNET_SOCK}" "${UML4TERMUX_BESS_SOCK}" 2>/dev/null || true
  exit 0
}
trap cleanup TERM INT EXIT

# A fresh run starts with no forwards on record.
: >"${reg}" 2>/dev/null || true

while :; do
  if [ "${proot_flag}" = "1" ]; then
    proot -b "${PREFIX}/etc:/etc" "${bin}" -debug \
      -listen "unix://${UML4TERMUX_GVNET_SOCK}" \
      -listen-bess "unixpacket://${UML4TERMUX_BESS_SOCK}" \
      -log-file "${UML4TERMUX_GVPROXY_LOG}" &
  else
    "${bin}" -debug \
      -listen "unix://${UML4TERMUX_GVNET_SOCK}" \
      -listen-bess "unixpacket://${UML4TERMUX_BESS_SOCK}" \
      -log-file "${UML4TERMUX_GVPROXY_LOG}" &
  fi
  child=$!
  # The pidfile must point at the real gvproxy process, not the proot wrapper:
  # proot does not reliably forward SIGTERM to its tracee, so a stop that kills
  # the wrapper pid would leave gvproxy running as an orphan. pgrep -P finds the
  # tracee (gvproxy) once proot has started it.
  gpid=""
  for _ in $(seq 1 5); do
    gpid="$(pgrep -P "${child}" 2>/dev/null | head -1)"
    [ -n "${gpid}" ] && break
    sleep 0.3
  done
  printf '%s\n' "${gpid:-${child}}" >"${pidfile}"

  ready=0
  for _ in $(seq 1 40); do
    if [ -S "${UML4TERMUX_BESS_SOCK}" ] && [ -S "${UML4TERMUX_GVNET_SOCK}" ]; then
      ready=1
      break
    fi
    kill -0 "${child}" 2>/dev/null || break
    sleep 1
  done

  if [ "${ready}" = "1" ] && [ -s "${reg}" ]; then
    # Re-apply every recorded forward. A failed POST is not fatal: the next
    # restart tries again, and 'uml4termux expose' can always re-add one.
    while IFS= read -r spec; do
      [ -n "${spec}" ] || continue
      host="${spec%%:*}"
      guest="${spec##*:}"
      curl -sS -m 10 --unix-socket "${UML4TERMUX_GVNET_SOCK}" \
        -X POST -d "{\"local\":\"127.0.0.1:${host}\",\"remote\":\"${UML4TERMUX_GUEST_IP:-192.168.127.2}:${guest}\"}" \
        http://unix/services/forwarder/expose >/dev/null 2>&1 || true
    done <"${reg}"
  fi

  wait "${child}" 2>/dev/null || true
  child=""

  # Stop as soon as the UML instance is gone: net_stop kills UML first, then
  # this supervisor, so a surviving supervisor is a bug, not a restart.
  upid="$(tr -d ' \n' <"${runtime}/uml.pid" 2>/dev/null || echo 0)"
  if ! upid_alive "${upid}"; then break; fi
  sleep 1
done
cleanup
SUP
}

# ---------------------------------------------------------------------------
# port exposure registry (what must be re-applied after a gvproxy restart)
# ---------------------------------------------------------------------------
net_expose_registry() { printf '%s/expose.list' "${UML4TERMUX_RUNTIME}"; }

net_expose_register() {
  local spec="$1" reg
  reg="$(net_expose_registry)"
  uml4termux_runtime_init
  if ! grep -qxF "${spec}" "${reg}" 2>/dev/null; then
    printf '%s\n' "${spec}" >>"${reg}"
  fi
}

net_expose_unregister() {
  local spec="$1" reg tmp
  reg="$(net_expose_registry)"
  [ -f "${reg}" ] || return 0
  tmp="${reg}.tmp.$$"
  grep -vxF "${spec}" "${reg}" >"${tmp}" 2>/dev/null || : >"${tmp}"
  mv -f "${tmp}" "${reg}" 2>/dev/null || rm -f "${tmp}"
}

net_expose_apply_all() {
  # Re-issue every recorded forward against the running gvproxy.
  local reg host guest spec
  reg="$(net_expose_registry)"
  [ -s "${reg}" ] || return 0
  while IFS= read -r spec; do
    [ -n "${spec}" ] || continue
    host="${spec%%:*}"
    guest="${spec##*:}"
    uml4termux_run curl -sS -m 10 --unix-socket "${UML4TERMUX_GVNET_SOCK}" \
      -X POST -d "{\"local\":\"127.0.0.1:${host}\",\"remote\":\"${UML4TERMUX_GUEST_IP}:${guest}\"}" \
      http://unix/services/forwarder/expose >/dev/null 2>&1 || true
    info "re-exposed 127.0.0.1:${host} -> guest ${UML4TERMUX_GUEST_IP}:${guest} (registry)"
  done <"${reg}"
}

net_wait_ready() {
  local timeout="${1:-40}" i pid
  if uml4termux_is_dry_run; then
    printf '+ (wait up to %ss for %s and %s)\n' "${timeout}" "${UML4TERMUX_BESS_SOCK}" "${UML4TERMUX_GVNET_SOCK}"
    return 0
  fi
  for ((i = 0; i < timeout; i++)); do
    if [ -S "${UML4TERMUX_BESS_SOCK}" ] && [ -S "${UML4TERMUX_GVNET_SOCK}" ]; then
      ok "gvproxy up: control ${UML4TERMUX_GVNET_SOCK}, bess ${UML4TERMUX_BESS_SOCK}"
      return 0
    fi
    pid="$(uml4termux_read_pid gvproxy)"
    if [ -n "${pid}" ] && ! uml4termux_pid_alive "${pid}"; then
      err "gvproxy died during startup (pid ${pid})"
      uml4termux_tail "${UML4TERMUX_GVPROXY_LOG}" 20
      return 1
    fi
    sleep 1
  done
  err "gvproxy did not create its sockets within ${timeout}s"
  uml4termux_tail "${UML4TERMUX_GVPROXY_LOG}" 20
  return 1
}

net_gvproxy_alive() {
  local pid; pid="$(uml4termux_read_pid gvproxy)"
  uml4termux_pid_alive "${pid}"
}

net_health() {
  # GET /services/forwarder/all is the lightest control-plane probe.
  uml4termux_run curl -sS -m 10 --unix-socket "${UML4TERMUX_GVNET_SOCK}" \
    http://unix/services/forwarder/all
}

net_stop() {
  # Order matters: kill UML first so gvproxy sees the BESS peer EOF, then
  # gvproxy.  gvproxy exits by itself on peer disconnect, so a missing process
  # here is normal, not an error.  Killing the gvproxy pid kills its supervisor
  # (the pidfile holds the live child, and the supervisor dies with it), which
  # must be given a moment to reap that child and remove the sockets.
  step "stopping uml4termux instance"
  uml4termux_kill_label uml
  uml4termux_kill_label gvproxy
  if uml4termux_is_dry_run; then
    printf '+ rm -f %s\n' "$(uml4termux_quote "${UML4TERMUX_GVNET_SOCK}" "${UML4TERMUX_BESS_SOCK}")"
    printf '+ rm -rf %s\n' "${HOME}/.uml/${UML4TERMUX_UMID}"
    return 0
  fi
  local i pid
  for ((i = 0; i < 5; i++)); do
    pid="$(uml4termux_read_pid gvproxy)"
    if ! uml4termux_pid_alive "${pid}"; then break; fi
    sleep 1
  done
  rm -f "${UML4TERMUX_GVNET_SOCK}" "${UML4TERMUX_BESS_SOCK}" "$(net_expose_registry)"
  # kernel umid dir (~/.uml/<umid>): only removed when no UML process is left
  local upid; upid="$(uml4termux_read_pid uml)"
  if ! uml4termux_pid_alive "${upid}"; then
    rm -rf "${HOME}/.uml/${UML4TERMUX_UMID}" 2>/dev/null || true
  fi
  uml4termux_instance_clear
  rm -f "$(uml4termux_pidfile uml)" "$(uml4termux_pidfile gvproxy)"
  # The wake lock belongs to the instance, not to the command that took it:
  # the guest keeps running in the background, so it must be released here.
  uml4termux_wakelock_release
  ok "instance stopped"
}

# ---------------------------------------------------------------------------
# port forwarding (host loopback -> guest)
# ---------------------------------------------------------------------------
net_parse_mapping() {
  # "8123" or "8123:80" -> "8123 8123" / "8123 80"
  local spec="$1" host guest
  host="${spec%%:*}"
  if [ "${spec}" = "${host}" ]; then guest="${host}"; else guest="${spec##*:}"; fi
  case "${host}" in ''|*[!0-9]*) die "bad port specification: '${spec}' (expected HOSTPORT[:GUESTPORT])" ;; esac
  case "${guest}" in ''|*[!0-9]*) die "bad guest port in: '${spec}'" ;; esac
  printf '%s %s' "${host}" "${guest}"
}

net_expose() {
  local spec="$1" host guest parsed
  parsed="$(net_parse_mapping "${spec}")"
  host="${parsed%% *}"; guest="${parsed##* }"
  if ! uml4termux_is_dry_run; then
    net_gvproxy_alive || die "gvproxy is not running; expose needs a live instance (see 'uml4termux docker')"
  fi
  local payload
  payload="$(printf '{"local":"127.0.0.1:%s","remote":"%s:%s"}' "${host}" "${UML4TERMUX_GUEST_IP}" "${guest}")"
  uml4termux_run curl -sS -m 10 --unix-socket "${UML4TERMUX_GVNET_SOCK}" \
    -X POST -d "${payload}" http://unix/services/forwarder/expose
  net_expose_register "${spec}"
  info "exposed 127.0.0.1:${host} -> guest ${UML4TERMUX_GUEST_IP}:${guest}"
}

net_unexpose() {
  local spec="$1" host guest parsed
  parsed="$(net_parse_mapping "${spec}")"
  host="${parsed%% *}"; guest="${parsed##* }"
  if ! uml4termux_is_dry_run; then
    net_gvproxy_alive || die "gvproxy is not running"
  fi
  local payload
  payload="$(printf '{"local":"127.0.0.1:%s","remote":"%s:%s"}' "${host}" "${UML4TERMUX_GUEST_IP}" "${guest}")"
  uml4termux_run curl -sS -m 10 --unix-socket "${UML4TERMUX_GVNET_SOCK}" \
    -X POST -d "${payload}" http://unix/services/forwarder/unexpose >/dev/null
  net_expose_unregister "${spec}"
  info "unexposed 127.0.0.1:${host}"
}

# net_verify_port <port> [timeout] -> prints HTTP result, rc 0 when reachable
net_verify_port() {
  local port="$1" timeout="${2:-8}" out rc=0
  if uml4termux_is_dry_run; then
    printf '+ curl -sS -m %s -o - http://127.0.0.1:%s/\n' "${timeout}" "${port}"
    return 0
  fi
  if command -v curl >/dev/null 2>&1; then
    out="$(curl -sS -m "${timeout}" -o - "http://127.0.0.1:${port}/" 2>&1)" || rc=$?
  else
    out="$(uml4termux_python - "${port}" "${timeout}" <<'PYEOF'
import socket, sys
port, t = int(sys.argv[1]), float(sys.argv[2])
try:
    s = socket.create_connection(('127.0.0.1', port), timeout=t)
    s.sendall(b'GET / HTTP/1.0\r\nHost: localhost\r\n\r\n')
    data = s.recv(300).decode('utf-8', 'replace').strip().replace('\r', '')
    s.close()
    print(data)
except Exception as e:  # noqa: BLE001 - report the failure verbatim
    print('FAIL', type(e).__name__, e)
    sys.exit(1)
PYEOF
)" || rc=$?
  fi
  if [ "${rc}" -ne 0 ] || [ -z "${out}" ]; then
    printf 'FAIL\t127.0.0.1:%s\t%s\n' "${port}" "${out:-no response}"
    return 1
  fi
  printf 'OK\t127.0.0.1:%s\t%s\n' "${port}" "$(printf '%s' "${out}" | head -1)"
  return 0
}
